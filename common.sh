#!/usr/bin/env bash
# Shared settings for start-all.sh, stop-all.sh, status.sh and e2e-test.sh.
PLATFORM_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CAPSTONE_DIR="${CAPSTONE_DIR:-$(cd "$PLATFORM_DIR/.." && pwd)}"
RUN_DIR="$PLATFORM_DIR/run"
LOG_DIR="$PLATFORM_DIR/logs"
mkdir -p "$RUN_DIR" "$LOG_DIR"

# Start order matters: User Service first (others validate tokens with it), gateway last
SERVICES=(userservice productservice orderservice paymentservice cartservice notificationservice apigateway)
declare -A PORTS=([userservice]=8082 [productservice]=8080 [paymentservice]=8083 [orderservice]=8084
                  [cartservice]=8085 [notificationservice]=8086 [apigateway]=8000)

# Shared secrets: generated once per machine into .env (git-ignored)
ENV_FILE="$PLATFORM_DIR/.env"
if [ ! -f "$ENV_FILE" ]; then
  rnd() { head -c 24 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 32; }
  cat > "$ENV_FILE" <<ENV
# Generated by platform scripts. Shared by the services; keep private.
INTERNAL_API_TOKEN=$(rnd)
RAZORPAY_WEBHOOK_SECRET=$(rnd)
ADMIN_EMAILS=admin@ecom.local
ENV
  echo "Created $ENV_FILE with new random secrets"
fi
set -a; source "$ENV_FILE"; set +a

# Java 21 for the services (Elasticsearch uses its own bundled JDK)
if [ -z "${JAVA_HOME:-}" ] && [ -d "/c/Program Files/Eclipse Adoptium/jdk-21.0.12.101-hotspot" ]; then
  export JAVA_HOME="/c/Program Files/Eclipse Adoptium/jdk-21.0.12.101-hotspot"
fi
JAVA="${JAVA_HOME:+$JAVA_HOME/bin/}java"

port_open() { (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null; }
wait_port() { # name port timeout-seconds
  for _ in $(seq "$3"); do port_open "$2" && return 0; sleep 1; done
  echo "  !! $1 did not open port $2 within $3 s (see $LOG_DIR/$1.log)"; return 1
}
